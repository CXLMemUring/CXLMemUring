#!/usr/bin/env python3

import json
import os
import re
import sys
import tempfile
from pathlib import Path


SYMBOL_RE = re.compile(r"__cira_rv64_([0-9a-f]{16})\Z")
SCALAR_RE = re.compile(r"([if])(\d+)\Z")


def fail(message: str) -> None:
    raise ValueError(message)


def argument_size_and_alignment(type_name: str) -> tuple[int, int]:
    if type_name in ("arena_offset", "index"):
        return 8, 8
    match = SCALAR_RE.fullmatch(type_name)
    if not match:
        fail(f"unsupported argument type {type_name!r}")
    kind, width_text = match.groups()
    width = int(width_text)
    if kind == "f" and width not in (16, 32, 64):
        fail(f"unsupported floating-point width f{width}")
    if kind == "i" and not 1 <= width <= 64:
        fail(f"unsupported integer width i{width}")
    size = max(1, (width + 7) // 8)
    alignment = min(1 << (size - 1).bit_length(), 8)
    return size, alignment


def parse_kernel(record: object) -> dict:
    if not isinstance(record, dict):
        fail("kernel entry is not an object")
    if record.get("read_only") is not True:
        fail("every RV64 dispatch kernel must be read-only")

    raw_id = record.get("kernel_id")
    if not isinstance(raw_id, str) or not re.fullmatch(r"0x[0-9a-fA-F]{1,16}", raw_id):
        fail(f"invalid kernel ID {raw_id!r}")
    kernel_id = int(raw_id, 16)
    if kernel_id == 0:
        fail("kernel ID zero is reserved")

    symbol = record.get("symbol")
    match = SYMBOL_RE.fullmatch(symbol) if isinstance(symbol, str) else None
    if not match or int(match.group(1), 16) != kernel_id:
        fail(f"symbol {symbol!r} does not match kernel ID 0x{kernel_id:016x}")

    arguments = record.get("args")
    if not isinstance(arguments, list):
        fail(f"kernel 0x{kernel_id:016x} has no argument layout")
    previous_end = 0
    names: set[str] = set()
    for argument in arguments:
        if not isinstance(argument, dict):
            fail(f"kernel 0x{kernel_id:016x} has a malformed argument")
        name = argument.get("name")
        offset = argument.get("offset")
        type_name = argument.get("type")
        if not isinstance(name, str) or not name or name in names:
            fail(f"kernel 0x{kernel_id:016x} has an invalid or duplicate argument name")
        if not isinstance(offset, int) or isinstance(offset, bool) or offset < 0:
            fail(f"kernel 0x{kernel_id:016x} has an invalid argument offset")
        if not isinstance(type_name, str):
            fail(f"kernel 0x{kernel_id:016x} has an invalid argument type")
        size, alignment = argument_size_and_alignment(type_name)
        if offset < previous_end or offset % alignment:
            fail(f"kernel 0x{kernel_id:016x} has an overlapping or misaligned argument layout")
        previous_end = offset + size
        names.add(name)

    expected_size = (previous_end + 7) & ~7
    args_size = record.get("args_size")
    if not isinstance(args_size, int) or isinstance(args_size, bool) or args_size != expected_size:
        fail(f"kernel 0x{kernel_id:016x} args_size {args_size!r} does not match layout size {expected_size}")
    if args_size > 0xFFFFFFFF:
        fail(f"kernel 0x{kernel_id:016x} argument block is too large")
    return {"kernel_id": kernel_id, "symbol": symbol, "args_size": args_size}


def generate(manifest: object) -> str:
    if not isinstance(manifest, dict) or manifest.get("abi_version") != 2:
        fail("manifest ABI version must be 2")
    records = manifest.get("kernels")
    if not isinstance(records, list) or not records:
        fail("manifest must contain at least one kernel")

    kernels = sorted((parse_kernel(record) for record in records), key=lambda entry: entry["kernel_id"])
    for left, right in zip(kernels, kernels[1:]):
        if left["kernel_id"] == right["kernel_id"]:
            fail(f"duplicate kernel ID 0x{left['kernel_id']:016x}")

    lines = [
        "// Generated by gen_dispatch_table.py; do not edit.",
        "#ifndef CIRA_RV64_DISPATCH_GENERATED_H",
        "#define CIRA_RV64_DISPATCH_GENERATED_H",
        "",
    ]
    for entry in kernels:
        lines.append(f"extern void {entry['symbol']}(uint64_t, uint64_t);")
    lines.extend(["", "static const struct cira_kernel_entry cira_kernel_table[] = {"])
    for entry in kernels:
        lines.append(
            f"    {{ UINT64_C(0x{entry['kernel_id']:016x}), {entry['symbol']}, {entry['args_size']} }},"
        )
    lines.extend(
        [
            "};",
            "static const size_t cira_kernel_table_count =",
            "    sizeof(cira_kernel_table) / sizeof(cira_kernel_table[0]);",
            "",
            "#endif",
            "",
        ]
    )
    return "\n".join(lines)


def main() -> int:
    if len(sys.argv) != 3:
        print(f"usage: {sys.argv[0]} MANIFEST OUTPUT", file=sys.stderr)
        return 2
    manifest_path = Path(sys.argv[1])
    output_path = Path(sys.argv[2])
    try:
        manifest = json.loads(manifest_path.read_text(encoding="utf-8"))
        content = generate(manifest)
        output_path.parent.mkdir(parents=True, exist_ok=True)
        with tempfile.NamedTemporaryFile(
            mode="w", encoding="utf-8", dir=output_path.parent, prefix=output_path.name + ".", delete=False
        ) as temporary:
            temporary.write(content)
            temporary_path = Path(temporary.name)
        os.replace(temporary_path, output_path)
    except (OSError, json.JSONDecodeError, ValueError) as error:
        print(f"gen_dispatch_table.py: {error}", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
